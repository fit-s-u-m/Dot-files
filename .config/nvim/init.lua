-- Define a function to run a command in a full-screen terminal
function RunShellCommand(command)
	-- Open a new full-screen terminal
	vim.cmd("new | term")
	-- Get the current buffer number (the terminal buffer)
	local bufnr = vim.api.nvim_get_current_buf()
	-- Send the command to the terminal
	vim.fn.chansend(vim.b.terminal_job_id, command .. "\n")
	-- Define an autocmd to close the terminal when the command finishes
	vim.cmd('autocmd TermClose <buffer> execute "bwipeout! " .. ' .. bufnr)
end

-- Create a custom command to use the function
vim.api.nvim_create_user_command("RunTerm", function(opts)
	RunShellCommand(opts.args)
end, { nargs = 1 })

-- Optionally, create a key mapping for convenience
